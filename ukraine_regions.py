def search_oblasts(prefix, limit=10):
    prefix_lower = prefix.strip().lower()
    if not prefix_lower:
        return OBLASTS[:limit]
    starts = [o for o in OBLASTS if o.lower().startswith(prefix_lower)]
    contains = [o for o in OBLASTS if prefix_lower in o.lower() and o not in starts]
    return (starts + contains)[:limit]
