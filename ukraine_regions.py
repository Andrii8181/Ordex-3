def search_oblasts(prefix, limit=10):
    prefix_lower = prefix.strip().lower()
    if not prefix_lower:
        return OBLASTS[:limit]
    starts = [o for o in OBLASTS if o.lower().startswith(prefix_lower)]
    contains = [o for o in OBLASTS if prefix_lower in o.lower() and o not in starts]
    return (starts + contains)[:limit]


def search_cities_static(oblast, prefix, limit=10):
    """Пошук серед вбудованого довідника міст для заданої області."""
    cities = CITIES_BY_OBLAST.get(oblast, [])
    prefix_lower = prefix.strip().lower()
    if not prefix_lower:
        return cities[:limit]
    starts = [c for c in cities if c.lower().startswith(prefix_lower)]
    contains = [c for c in cities if prefix_lower in c.lower() and c not in starts]
    return (starts + contains)[:limit]
